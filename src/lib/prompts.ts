// --------------------------------------------------
// 5. 对话模式 - LLM 根据人格锚点 + 人格输出控制指令 与用户对话
// --------------------------------------------------
export function chatSystemPrompt(persona: string, memory?: { role: string; content: string }[], personaProtocol?: string): string {
  let memorySection = '';
  if (memory && memory.length > 0) {
    // 只取最近的对话记忆，避免 token 过长
    const recentMemory = memory.slice(-20);
    const memoryText = recentMemory
      .map(m => `${m.role === 'user' ? '用户' : '我'}：${m.content}`)
      .join('\n');
    memorySection = `\n\n【与该用户的历史记忆】\n${memoryText}\n\n注意：以上是你与当前用户过去对话的记忆。请自然地延续之前的对话氛围，如果用户提到之前聊过的话题，要记得并自然回应，但不要主动重复之前说过的话。`;
  }

  // 人格输出控制指令部分（v3 新增：Agentic Protocol）
  let protocolSection = '';
  if (personaProtocol && personaProtocol.trim()) {
    protocolSection = `\n\n【人格输出控制指令（Agentic Protocol）】\n${personaProtocol}\n\n你必须严格遵守上述人格输出控制指令中的规则，它是你对话行为的"操作系统"。`;
  }

  return `${persona}
${protocolSection}
${memorySection}

回复要求：
1. 严格保持角色人格锚点中定义的身份和性格
2. 用符合角色说话风格和语言习惯的方式回答
3. 回复要有情感和个性，不要机械化
4. 可以适当使用表情符号增加趣味性
5. 回复长度控制在100-200字
6. 如果用户问及你的故事或性格，按照人格锚点中的设定热情分享
7. 如果有历史记忆，要自然地体现出你对之前对话的记得，但不要生硬地复述`;
}

